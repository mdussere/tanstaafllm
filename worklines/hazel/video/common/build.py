"""Build an episode from its script: timeline, page, score, reading audit, layout lint, NOTES.md, video.

  uv run --project <repo> python common/build.py episodes/<episode>.yaml [--preview | --full] [--out DIR] [--no-video]

  --preview  640x360 at 10 fps (fast; the same picture scaled down)       --full  1920x1080 at 30 fps
Output (default <repo>/results/hazel/<episode>/<timestamp>/): index.html (+ fonts/, art/), music.wav, hits.json,
audit.md, lint.txt, NOTES.md, contact.png (12 thumbnails, 960 px wide), stills/, <name>.mp4.
"""
import argparse
import datetime
import json
import pathlib
import shutil
import subprocess
import sys

import numpy as np
import yaml

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import audit as AU          # noqa: E402
import capture as CAP       # noqa: E402
import contact as CT        # noqa: E402
import cues                 # noqa: E402
import lint as LN           # noqa: E402
import slots as SL          # noqa: E402

REPO = HERE.parents[3]
META = ('events', 'facts', 'picture', 'music_note')


def timeline(ep):
    beat = 60.0 / ep.get('bpm', 120)
    t, scenes = 0.0, []
    for i, sc in enumerate(ep['scenes']):
        t1 = round(t + sc['bars'] * 4 * beat, 6)
        scenes.append(dict(sc, index=i, t0=round(t, 6), t1=t1))
        t = t1
    return scenes


def make_page(ep, scenes, holds, out):
    page_scenes = [{'template': s['template'], 't0': s['t0'], 't1': s['t1'], 'p': {k: v for k, v in s.items() if k not in META}}
                   for s in scenes]
    data = dict(scenes=page_scenes, holds=holds, base=scenes[-1]['t1'], stages=ep.get('stages', 7), boss_stage=ep.get('boss_stage', 0))
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{ep['title']}</title>
<style>
  @font-face {{ font-family: 'PS2P'; src: url('fonts/pressstart2p_PressStart2P-Regular.ttf'); }}
  @font-face {{ font-family: 'VT'; src: url('fonts/vt323_VT323-Regular.ttf'); }}
  html, body {{ margin: 0; padding: 0; background: #000; overflow: hidden; }}
  canvas {{ display: block; width: 100vw; height: 100vh; }}
</style>
</head>
<body>
<canvas id="c" width="1920" height="1080"></canvas>
<script>
// Generated by common/build.py from the episode script; do not edit. Open with ?t=12.5 for one frame, ?play to loop.
const EPISODE = {json.dumps(data)};
{(HERE / 'runtime.js').read_text()}
{(HERE / 'templates.js').read_text()}
</script>
</body>
</html>
"""
    (out / 'index.html').write_text(html)
    for d in ('fonts', 'art'):
        shutil.copytree(HERE / d, out / d, dirs_exist_ok=True)


def notes_md(ep, scenes, rows, lint_summary, out_name, meta):
    L = [f"# {ep['title']} (generated from episodes/{ep['episode']}.yaml)", '',
         f"{meta['duration']:.1f} s, {meta['size']} at {meta['fps']} fps. Built by common/build.py; do not edit by hand, edit the script.", '',
         '## Structure (seconds of the cut, before reading holds)', '', '| Time | Template | Picture | Music |', '|---|---|---|---|']
    for s in scenes:
        L.append(f"| {s['t0']:g}-{s['t1']:g} | {s['template']} {s['id']} ({s['bars']} bars) | {s.get('picture', '')} | {s.get('music_note', '')} |")
    L += ['', '## Every on-screen fact and its source', '', '| Scene | On screen | Source | Machine shown |', '|---|---|---|---|']
    for s in scenes:
        for f in s.get('facts', []):
            L.append(f"| {s['id']} | {f['on_screen']} | {f['source']} | {f.get('machine', '-')} |")
    L += ['', '## Reading audit', '', AU.table(rows)[0], '', '## Layout lint', '', lint_summary, '', '## Files', '',
          f'`{out_name}`, `music.wav`, `hits.json`, `audit.md`, `lint.txt`, `contact.png`, `index.html`.']
    return '\n'.join(L) + '\n'


def contact_times(scenes, ep):
    ts = []
    for s in scenes:
        sl = SL.SLOTS[s['template']](s, ep)
        lead = s.get('cut_lead', SL.LEAD.get(s['template'], 0.0))
        r = s.get('still', (max(x[0] for x in sl) + 0.3) if sl else (s['t1'] - s['t0']) * 0.6)
        ts.append(round(min(s['t0'] + r, s['t1'] - lead - 0.05), 2))
    return ts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('episode')
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--preview', action='store_true', help='640x360 at 10 fps (default)')
    g.add_argument('--full', action='store_true', help='1920x1080 at 30 fps')
    ap.add_argument('--out')
    ap.add_argument('--no-video', action='store_true', help='skip the video, keep page, score, audit, lint, contact sheet')
    ap.add_argument('--lint-step', type=float, default=0.5)
    a = ap.parse_args()

    ep = yaml.safe_load(pathlib.Path(a.episode).read_text())
    size, fps = ((1920, 1080), 30) if a.full else ((640, 360), 10)
    stamp = datetime.datetime.now().strftime('%Y%m%dT%H%M%S')
    out = pathlib.Path(a.out) if a.out else REPO / 'results' / 'hazel' / ep['episode'] / stamp
    out.mkdir(parents=True, exist_ok=True)

    scenes = timeline(ep)
    rows = AU.audit(scenes, ep)
    table, extra = AU.table(rows)
    holds = [[r['cut'], r['hold']] for r in rows if r['hold'] > 0]
    (out / 'audit.md').write_text(table + '\n')
    print(f'audit: holds +{extra:.1f} s, duration {scenes[-1]["t1"] + extra:.1f} s')

    make_page(ep, scenes, holds, out)
    ctx = dict(motif=ep.get('motif', []), riffs=ep.get('riffs', {}), stages=ep.get('stages', 7))
    x = cues.render(scenes, ctx, holds)
    cues.write_wav(out / 'music.wav', x)
    (out / 'hits.json').write_text(cues.hits_json())
    print(f'score: {len(x) / cues.SR:.3f} s, peak {20 * np.log10(np.abs(x).max()):.2f} dBFS')

    duration = scenes[-1]['t1'] + extra
    times = [round(i * a.lint_step, 3) for i in range(int(duration / a.lint_step))]
    rec, errors = CAP.lint_frames(out, times)
    # the page's times are output times; scene boundaries are source times, so map back through the holds
    findings, summary = LN.analyse(rec, scenes, holds)
    (out / 'lint.txt').write_text(findings)
    print(summary)

    ct = contact_times(scenes, ep)
    paths, err2 = CAP.render_stills(out, out / 'stills', ct, size)
    CT.sheet(out / 'contact.png', paths)
    errors += err2

    name = f"tanstaafllm-{ep['episode']}"
    if not a.no_video:
        errors += CAP.render_video(out, out / f'{name}.mp4', fps, out / 'music.wav', size,
                                   preset='slow' if a.full else 'veryfast', crf=16 if a.full else 23)
        r = subprocess.run(['ffmpeg', '-hide_banner', '-i', str(out / f'{name}.mp4'), '-af', 'ebur128=peak=true', '-f', 'null', '-'],
                           capture_output=True, text=True)
        summ = r.stderr.split('Summary:')[-1].split()
        loud = [f"{k} {summ[summ.index(k) + 1]} {summ[summ.index(k) + 2]}" for k in ('I:', 'Peak:') if k in summ]
        print('video:', out / f'{name}.mp4', *loud)
    (out / 'NOTES.md').write_text(notes_md(ep, scenes, rows, summary, f'{name}.mp4',
                                           dict(duration=duration, size=f'{size[0]}x{size[1]}', fps=fps)))
    if errors:
        print('PAGE ERRORS:', *errors, sep='\n', file=sys.stderr)
        sys.exit(1)
    print('out:', out)


if __name__ == '__main__':
    main()
